# Prints Currencies.js from a Sure image. To update it:
#   docker run --rm -i --entrypoint ruby ghcr.io/we-promise/sure:latest - < tests/vps/currencies.rb > Currencies.js
require "yaml"
require "json"

rows = YAML.load_file("/rails/config/currencies.yml").values.sort_by { |c| c["iso_code"] }.map do |c|
  first = (c["default_format"] || "%u%n").start_with?("%u") ? 1 : 0
  entry = [ c["symbol"], first, c["default_precision"] || 2, c["minor_unit_conversion"] || 100 ]
  "#{c["iso_code"]}:#{JSON.generate(entry)}"
end
puts ".pragma library"
puts
puts "// From Sure's config/currencies.yml: code -> [symbol, symbol first (1) or last (0), decimals, minor units per major]."
puts "// Generated by tests/vps/currencies.rb. tests/contract.test.js fails when a newer Sure disagrees."
puts "var TABLE = {"
puts "  " + rows.join(",\n  ")
puts "}"
